import fs from 'node:fs';
import ts from 'typescript';
import assert from 'node:assert/strict';
import {normalize} from '../collect.mjs';
const code=ts.transpileModule(fs.readFileSync('lib/catalog-text.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {decodeCatalogText,cleanCatalogText}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
assert.equal(decodeCatalogText('Women&#8217;s &amp; Men&#x2019;s'),'Women’s & Men’s');
assert.equal(decodeCatalogText('700&amp;#215;28'),'700×28');
assert.equal(decodeCatalogText('&quot;Trail&quot;&nbsp;&ndash;&nbsp;&reg;'),'"Trail" – ®');
assert.equal(decodeCatalogText('&#99999999; &#xD800;'),'&#99999999; &#xD800;');
const item={id:10,parent:0,name:'Women&#8217;s Jersey',categories:[{name:'Clothing &amp; Apparel'}],type:'simple',variation:'Size: M/L, Color: Black &amp; White',is_in_stock:true,permalink:'https://bikecloset.com/product/test/',prices:{currency_code:'USD',price:'1000',regular_price:'2000',currency_minor_unit:2}};
const {rows}=normalize([item],[],null,'2026-09-09T00:00:00Z');
assert.equal(rows[0].name,'Women’s Jersey');
assert.equal(rows[0].variant,'Size: M/L, Color: Black & White');
assert.equal(rows[0].category,'Clothing & Apparel');
assert.equal(rows[0].price,10);
assert.equal(rows[0].url,item.permalink);
assert.deepEqual(cleanCatalogText(rows[0]),rows[0]);
console.log('Shared text cleanup verified at feed ingestion; exact details, prices and links preserved.');
