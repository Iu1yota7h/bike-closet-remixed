import fs from 'node:fs';import ts from 'typescript';import assert from 'node:assert/strict';
const code=ts.transpileModule(fs.readFileSync('lib/catalog-attributes.ts','utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext}}).outputText;
const {catalogAttributes,matchesListingDetail,searchText}=await import('data:text/javascript;base64,'+Buffer.from(code).toString('base64'));
const a=name=>catalogAttributes({name});
assert.equal(a('sRaM chain').brand,'SRAM');
assert.equal(a('SRAM, Red chain').brand,'SRAM');
assert.equal(a('i9 Hydra hub').brand,'Industry Nine');
assert.equal(a('Selle Italia saddle').brand,'Selle Italia');
assert.equal(a('Lookalike saddle').brand,'');
assert.deepEqual(a('Unknown product'),{brand:'',condition:'',packaging:'',saleTerms:''});
const listing=a('Look pedal (OEM) (Open Box) (Final Sale)');
for(const flag of ['OEM','Open box','Final sale','all'])assert(matchesListingDetail(listing,flag));
assert.equal(a('Look pedal OEM').condition,'');
assert.equal(a('Look pedal OEM').saleTerms,'');
assert.equal(matchesListingDetail(a('Look pedal'),'Open box'),false);
assert.equal(searchText('Women’s 700 × 28'),searchText("Women's 700x28"));
assert.equal(searchText('KUNÈE — helmet'),searchText('Kunee - helmet'));
const rows=JSON.parse(fs.readFileSync('public/catalog.json')).rows.filter(r=>r.stock);
const attrs=rows.map(r=>({...r,...catalogAttributes(r)}));
console.log(JSON.stringify({inStock:rows.length,brands:new Set(attrs.map(r=>r.brand).filter(Boolean)).size,unknownBrands:[...new Set(attrs.filter(r=>!r.brand).map(r=>r.name))],openBox:attrs.filter(r=>r.condition).length,OEM:attrs.filter(r=>r.packaging).length,finalSale:attrs.filter(r=>r.saleTerms).length}));
console.log('Brand aliases, independent listing facts and punctuation-tolerant search passed.');
